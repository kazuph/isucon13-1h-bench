CREATE TABLE icon_objects (
  digest BINARY(32) NOT NULL PRIMARY KEY,
  image LONGBLOB NOT NULL
) ENGINE=InnoDB;
ALTER TABLE icons
  MODIFY COLUMN image LONGBLOB NULL,
  ADD COLUMN object_digest BINARY(32) NULL,
  MODIFY COLUMN image_hash CHAR(64) GENERATED ALWAYS AS
    (COALESCE(LOWER(HEX(object_digest)), SHA2(image,256))) STORED;
