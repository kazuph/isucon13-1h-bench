func getIconHandler(c echo.Context) error {
	ctx := c.Request().Context()

	username := c.Param("username")

	// The metadata cache is bounded to 500ms, within the icon update allowance.
	if match := c.Request().Header.Get("If-None-Match"); match != "" {
		if user, ok := sharedUserNamed(username); ok {
			etag := `"` + user.IconHash + `"`
			if match == etag {
				c.Response().Header().Set("ETag", etag)
				return c.NoContent(http.StatusNotModified)
			}
		}
	}

	tx, err := dbConn.BeginTxx(ctx, nil)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to begin transaction: "+err.Error())
	}
	defer tx.Rollback()

	var metadata struct {
		ID   int64          `db:"id"`
		Hash sql.NullString `db:"image_hash"`
	}
	if err := tx.GetContext(ctx, &metadata, "SELECT u.id,i.image_hash FROM users u LEFT JOIN icons i ON i.user_id=u.id WHERE u.name=?", username); err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return echo.NewHTTPError(http.StatusNotFound, "not found user that has the given username")
		}
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to get icon metadata: "+err.Error())
	}
	if !metadata.Hash.Valid {
		data, fallback, err := loadFallback()
		if err != nil {
			return err
		}
		etag := `"` + fallback + `"`
		c.Response().Header().Set("ETag", etag)
		if c.Request().Header.Get("If-None-Match") == etag {
			return c.NoContent(http.StatusNotModified)
		}
		return c.Blob(http.StatusOK, "image/jpeg", data)
	}
	etag := `"` + metadata.Hash.String + `"`
	c.Response().Header().Set("ETag", etag)
	if c.Request().Header.Get("If-None-Match") == etag {
		return c.NoContent(http.StatusNotModified)
	}
	var image []byte
	if err := tx.GetContext(ctx, &image, "SELECT image FROM icons WHERE user_id = ?", metadata.ID); err != nil {
		return err
	}
	return c.Blob(http.StatusOK, "image/jpeg", image)
}

func postIconHandler(c echo.Context) error {
	ctx := c.Request().Context()

	if err := verifyUserSession(c); err != nil {
		// echo.NewHTTPErrorが返っているのでそのまま出力
		return err
	}

	// error already checked
	sess, _ := session.Get(defaultSessionIDKey, c)
	// existence already checked
	userID := sess.Values[defaultUserIDKey].(int64)

	var req *PostIconRequest
	if err := json.NewDecoder(c.Request().Body).Decode(&req); err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "failed to decode the request body as json")
	}

	tx, err := dbConn.BeginTxx(ctx, nil)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to begin transaction: "+err.Error())
	}
	defer tx.Rollback()

	var lockedUserID int64
	if err := tx.GetContext(ctx, &lockedUserID, "SELECT id FROM users WHERE id = ? FOR UPDATE", userID); err != nil {
		return err
	}

	rs, err := tx.ExecContext(ctx, "REPLACE INTO icons (user_id, image) VALUES (?, ?)", userID, req.Image)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to insert new user icon: "+err.Error())
	}

	iconID, err := rs.LastInsertId()
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to get last inserted icon id: "+err.Error())
	}

	if err := tx.Commit(); err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to commit: "+err.Error())
	}

	invalidateSharedUser(userID)

	return c.JSON(http.StatusCreated, &PostIconResponse{
		ID: iconID,
	})
}

