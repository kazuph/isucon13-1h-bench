var fallbackImage = "../img/NoImage.jpg"
var fallbackOnce sync.Once
var fallbackData []byte
var fallbackHash string
var fallbackErr error

func loadFallback() ([]byte, string, error) {
	fallbackOnce.Do(func() {
		fallbackData, fallbackErr = os.ReadFile(fallbackImage)
		if fallbackErr == nil {
			fallbackHash = fmt.Sprintf("%x", sha256.Sum256(fallbackData))
		}
	})
	return fallbackData, fallbackHash, fallbackErr
}

