func getLivecommentReportsHandler(c echo.Context) error {
	ctx := c.Request().Context()

	if err := verifyUserSession(c); err != nil {
		return err
	}

	livestreamID, err := strconv.Atoi(c.Param("livestream_id"))
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "livestream_id in path must be integer")
	}

	livestreamModel, err := getLivestreamByID(ctx, int64(livestreamID))
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to get livestream: "+err.Error())
	}

	userID := sessionUserID(c)

	if livestreamModel.UserID != userID {
		return echo.NewHTTPError(http.StatusForbidden, "can't get other streamer's livecomment reports")
	}

	type row struct {
		ID          int64  `db:"id"`
		UserID      int64  `db:"user_id"`
		CreatedAt   int64  `db:"created_at"`
		LcID        int64  `db:"lc_id"`
		LcUserID    int64  `db:"lc_user_id"`
		LcLsID      int64  `db:"lc_livestream_id"`
		LcComment   string `db:"lc_comment"`
		LcTip       int64  `db:"lc_tip"`
		LcCreatedAt int64  `db:"lc_created_at"`
	}
	var rows []row
	if err := dbConn.SelectContext(ctx, &rows, `SELECT r.id, r.user_id, r.created_at, l.id AS lc_id, l.user_id AS lc_user_id, l.livestream_id AS lc_livestream_id, l.comment AS lc_comment, l.tip AS lc_tip, l.created_at AS lc_created_at
		FROM livecomment_reports r INNER JOIN livecomments l ON l.id = r.livecomment_id WHERE r.livestream_id = ? ORDER BY r.id`, livestreamID); err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to get livecomment reports: "+err.Error())
	}

	reports := make([]LivecommentReport, len(rows))
	for i, r := range rows {
		reporter, err := buildUserByID(ctx, r.UserID)
		if err != nil {
			return echo.NewHTTPError(http.StatusInternalServerError, "failed to fill livecomment report: "+err.Error())
		}
		lc, err := buildLivecomment(ctx, LivecommentModel{ID: r.LcID, UserID: r.LcUserID, LivestreamID: r.LcLsID, Comment: r.LcComment, Tip: r.LcTip, CreatedAt: r.LcCreatedAt})
		if err != nil {
			return echo.NewHTTPError(http.StatusInternalServerError, "failed to fill livecomment report: "+err.Error())
		}
		reports[i] = LivecommentReport{ID: r.ID, Reporter: reporter, Livecomment: lc, CreatedAt: r.CreatedAt}
	}

	return c.JSON(http.StatusOK, reports)
}

