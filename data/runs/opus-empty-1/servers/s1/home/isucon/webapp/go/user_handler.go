type sessInfo struct {
	userID  int64
	expires int64
}

var (
	sessCacheMu sync.RWMutex
	sessCache   = map[string]sessInfo{}

	pwCacheMu sync.RWMutex
	pwCache   = map[int64][32]byte{}
)

func sessionUserID(c echo.Context) int64 {
	if ck, err := c.Cookie(defaultSessionIDKey); err == nil {
		sessCacheMu.RLock()
		si, ok := sessCache[ck.Value]
		sessCacheMu.RUnlock()
		if ok {
			return si.userID
		}
	}
	sess, _ := session.Get(defaultSessionIDKey, c)
	return sess.Values[defaultUserIDKey].(int64)
}

func verifyUserSession(c echo.Context) error {
	ck, ckErr := c.Cookie(defaultSessionIDKey)
	if ckErr == nil {
		sessCacheMu.RLock()
		si, ok := sessCache[ck.Value]
		sessCacheMu.RUnlock()
		if ok {
			if time.Now().Unix() > si.expires {
				return echo.NewHTTPError(http.StatusUnauthorized, "session has expired")
			}
			return nil
		}
	}

	sess, err := session.Get(defaultSessionIDKey, c)
	if err != nil {
		return echo.NewHTTPError(http.StatusUnauthorized, "failed to get session")
	}

	sessionExpires, ok := sess.Values[defaultSessionExpiresKey]
	if !ok {
		return echo.NewHTTPError(http.StatusForbidden, "failed to get EXPIRES value from session")
	}

	uid, ok := sess.Values[defaultUserIDKey].(int64)
	if !ok {
		return echo.NewHTTPError(http.StatusUnauthorized, "failed to get USERID value from session")
	}

	exp, ok := sessionExpires.(int64)
	if !ok {
		return echo.NewHTTPError(http.StatusUnauthorized, "invalid EXPIRES value")
	}
	if ckErr == nil && !sess.IsNew {
		sessCacheMu.Lock()
		sessCache[ck.Value] = sessInfo{userID: uid, expires: exp}
		sessCacheMu.Unlock()
	}

	now := time.Now()
	if now.Unix() > exp {
		return echo.NewHTTPError(http.StatusUnauthorized, "session has expired")
	}

	return nil
}

