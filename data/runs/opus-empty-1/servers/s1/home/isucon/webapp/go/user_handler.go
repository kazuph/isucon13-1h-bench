func getIconHandler(c echo.Context) error {
	ctx := c.Request().Context()

	username := c.Param("username")

	user, err := getUserByName(ctx, username)
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return echo.NewHTTPError(http.StatusNotFound, "not found user that has the given username")
		}
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to get user: "+err.Error())
	}

	cacheMu.RLock()
	image, ok := iconDataUID[user.ID]
	h, hok := iconHashUID[user.ID]
	cacheMu.RUnlock()
	if !ok {
		image = fallbackBytes
		h = fallbackHash
	} else if !hok {
		h = fmt.Sprintf("%x", sha256.Sum256(image))
	}

	c.Response().Header().Set("ETag", "\""+h+"\"")
	c.Response().Header().Set("Cache-Control", "public, max-age=1")
	if inm := c.Request().Header.Get("If-None-Match"); inm != "" {
		inm = strings.TrimPrefix(inm, "W/")
		inm = strings.Trim(inm, "\"")
		if inm == h {
			return c.NoContent(http.StatusNotModified)
		}
	}

	return c.Blob(http.StatusOK, "image/jpeg", image)
}

func postIconHandler(c echo.Context) error {
	ctx := c.Request().Context()

	if err := verifyUserSession(c); err != nil {
		// echo.NewHTTPErrorが返っているのでそのまま出力
		return err
	}

	userID := sessionUserID(c)

	var req *PostIconRequest
	if err := json.NewDecoder(c.Request().Body).Decode(&req); err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "failed to decode the request body as json")
	}

	if _, err := dbConn.ExecContext(ctx, "DELETE FROM icons WHERE user_id = ?", userID); err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to delete old user icon: "+err.Error())
	}

	rs, err := dbConn.ExecContext(ctx, "INSERT INTO icons (user_id, image) VALUES (?, ?)", userID, req.Image)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to insert new user icon: "+err.Error())
	}

	iconID, err := rs.LastInsertId()
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to get last inserted icon id: "+err.Error())
	}
	cacheSetIcon(userID, req.Image)

	return c.JSON(http.StatusCreated, &PostIconResponse{
		ID: iconID,
	})
}

