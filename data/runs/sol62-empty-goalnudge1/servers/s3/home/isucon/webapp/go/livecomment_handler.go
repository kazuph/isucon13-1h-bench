func postLivecommentHandler(c echo.Context) error {
	ctx := c.Request().Context()
	defer c.Request().Body.Close()

	if err := verifyUserSession(c); err != nil {
		return err
	}

	livestreamID, err := strconv.Atoi(c.Param("livestream_id"))
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "livestream_id in path must be integer")
	}

	// error already checked
	sess, _ := session.Get(defaultSessionIDKey, c)
	// existence already checked
	userID := sess.Values[defaultUserIDKey].(int64)

	var req *PostLivecommentRequest
	if err := json.NewDecoder(c.Request().Body).Decode(&req); err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "failed to decode the request body as json")
	}

	tx, err := dbConn.BeginTxx(ctx, nil)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to begin transaction: "+err.Error())
	}
	defer tx.Rollback()

	var livestreamModel LivestreamModel
	if err := tx.GetContext(ctx, &livestreamModel, "SELECT * FROM livestreams WHERE id = ? FOR SHARE", livestreamID); err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return echo.NewHTTPError(http.StatusNotFound, "livestream not found")
		} else {
			return echo.NewHTTPError(http.StatusInternalServerError, "failed to get livestream: "+err.Error())
		}
	}

	// スパム判定
	var hitSpam bool
	if err := tx.GetContext(ctx, &hitSpam, `
		SELECT EXISTS (
			SELECT 1 FROM ng_words
			WHERE livestream_id = ? AND user_id = ?
			AND ? LIKE CONCAT('%', word, '%') COLLATE utf8mb4_general_ci
		)`, livestreamModel.ID, livestreamModel.UserID, req.Comment); err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to check NG words: "+err.Error())
	}
	if hitSpam {
		return echo.NewHTTPError(http.StatusBadRequest, "このコメントがスパム判定されました")
	}

	now := time.Now().Unix()
	livecommentModel := LivecommentModel{
		UserID:       userID,
		LivestreamID: int64(livestreamID),
		Comment:      req.Comment,
		Tip:          req.Tip,
		CreatedAt:    now,
	}

	rs, err := tx.NamedExecContext(ctx, "INSERT INTO livecomments (user_id, livestream_id, comment, tip, created_at) VALUES (:user_id, :livestream_id, :comment, :tip, :created_at)", livecommentModel)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to insert livecomment: "+err.Error())
	}

	livecommentID, err := rs.LastInsertId()
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to get last inserted livecomment id: "+err.Error())
	}
	livecommentModel.ID = livecommentID

	commentOwner, err := loadUser(ctx, tx, livecommentModel.UserID)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to fill livecomment author: "+err.Error())
	}
	livestream, err := fillLivestreamResponse(ctx, tx, livestreamModel)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to fill livestream: "+err.Error())
	}
	livecomment := livecommentResponse(livecommentModel, commentOwner, livestream)

	if err := tx.Commit(); err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to commit: "+err.Error())
	}

	return c.JSON(http.StatusCreated, livecomment)
}

func reportLivecommentHandler(c echo.Context) error {
	ctx := c.Request().Context()

	if err := verifyUserSession(c); err != nil {
		return err
	}

	livestreamID, err := strconv.Atoi(c.Param("livestream_id"))
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "livestream_id in path must be integer")
	}

	livecommentID, err := strconv.Atoi(c.Param("livecomment_id"))
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "livecomment_id in path must be integer")
	}

	// error already checked
	sess, _ := session.Get(defaultSessionIDKey, c)
	// existence already checked
	userID := sess.Values[defaultUserIDKey].(int64)

	tx, err := dbConn.BeginTxx(ctx, nil)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to begin transaction: "+err.Error())
	}
	defer tx.Rollback()

	var livestreamModel LivestreamModel
	if err := tx.GetContext(ctx, &livestreamModel, "SELECT * FROM livestreams WHERE id = ?", livestreamID); err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return echo.NewHTTPError(http.StatusNotFound, "livestream not found")
		} else {
			return echo.NewHTTPError(http.StatusInternalServerError, "failed to get livestream: "+err.Error())
		}
	}

	var livecommentModel LivecommentModel
	if err := getReportableLivecomment(ctx, tx, &livecommentModel, int64(livestreamID), int64(livecommentID)); err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return echo.NewHTTPError(http.StatusNotFound, "livecomment not found")
		} else {
			return echo.NewHTTPError(http.StatusInternalServerError, "failed to get livecomment: "+err.Error())
		}
	}

	now := time.Now().Unix()
	reportModel := LivecommentReportModel{
		UserID:        int64(userID),
		LivestreamID:  int64(livestreamID),
		LivecommentID: int64(livecommentID),
		CreatedAt:     now,
	}
	rs, err := tx.NamedExecContext(ctx, "INSERT INTO livecomment_reports(user_id, livestream_id, livecomment_id, created_at) VALUES (:user_id, :livestream_id, :livecomment_id, :created_at)", &reportModel)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to insert livecomment report: "+err.Error())
	}
	reportID, err := rs.LastInsertId()
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to get last inserted livecomment report id: "+err.Error())
	}
	reportModel.ID = reportID

	users, err := loadUsers(ctx, tx, []int64{userID, livecommentModel.UserID, livestreamModel.UserID})
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to load report profiles: "+err.Error())
	}
	reporter, reporterOK := users[userID]
	author, authorOK := users[livecommentModel.UserID]
	owner, ownerOK := users[livestreamModel.UserID]
	if !reporterOK || !authorOK || !ownerOK {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to find report profiles")
	}
	stream := livestreamResponse(livestreamModel, owner)
	report := livecommentReportResponse(reportModel, reporter, livecommentResponse(livecommentModel, author, stream))

	if err := tx.Commit(); err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to commit: "+err.Error())
	}

	return c.JSON(http.StatusCreated, report)
}

// NGワードを登録
func moderateHandler(c echo.Context) error {
	ctx := c.Request().Context()
	defer c.Request().Body.Close()

	if err := verifyUserSession(c); err != nil {
		return err
	}

	livestreamID, err := strconv.Atoi(c.Param("livestream_id"))
	if err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "livestream_id in path must be integer")
	}

	// error already checked
	sess, _ := session.Get(defaultSessionIDKey, c)
	// existence already checked
	userID := sess.Values[defaultUserIDKey].(int64)

	var req *ModerateRequest
	if err := json.NewDecoder(c.Request().Body).Decode(&req); err != nil {
		return echo.NewHTTPError(http.StatusBadRequest, "failed to decode the request body as json")
	}

	tx, err := dbConn.BeginTxx(ctx, nil)
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to begin transaction: "+err.Error())
	}
	defer tx.Rollback()

	// 配信者自身の配信に対するmoderateなのかを検証
	var ownedLivestreams []LivestreamModel
	if err := tx.SelectContext(ctx, &ownedLivestreams, "SELECT * FROM livestreams WHERE id = ? AND user_id = ? FOR UPDATE", livestreamID, userID); err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to get livestreams: "+err.Error())
	}
	if len(ownedLivestreams) == 0 {
		return echo.NewHTTPError(http.StatusBadRequest, "A streamer can't moderate livestreams that other streamers own")
	}

	rs, err := tx.NamedExecContext(ctx, "INSERT INTO ng_words(user_id, livestream_id, word, created_at) VALUES (:user_id, :livestream_id, :word, :created_at)", &NGWord{
		UserID:       int64(userID),
		LivestreamID: int64(livestreamID),
		Word:         req.NGWord,
		CreatedAt:    time.Now().Unix(),
	})
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to insert new NG word: "+err.Error())
	}

	wordID, err := rs.LastInsertId()
	if err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to get last inserted NG word id: "+err.Error())
	}

	// Keep report evidence available after removing a comment from the timeline.
	if _, err := tx.ExecContext(ctx, `
		INSERT INTO moderated_livecomments (id, user_id, livestream_id, comment, tip, created_at)
		SELECT id, user_id, livestream_id, comment, tip, created_at FROM livecomments
		WHERE livestream_id = ? AND EXISTS (
			SELECT 1 FROM ng_words
			WHERE ng_words.livestream_id = livecomments.livestream_id
			AND livecomments.comment LIKE CONCAT('%', ng_words.word, '%') COLLATE utf8mb4_general_ci
		)`, livestreamID); err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to archive moderated comments: "+err.Error())
	}
	if _, err := tx.ExecContext(ctx, `
		DELETE c FROM livecomments c
		JOIN moderated_livecomments m ON m.id = c.id
		WHERE c.livestream_id = ?`, livestreamID); err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to remove moderated comments: "+err.Error())
	}

	if err := tx.Commit(); err != nil {
		return echo.NewHTTPError(http.StatusInternalServerError, "failed to commit: "+err.Error())
	}

	return c.JSON(http.StatusCreated, map[string]interface{}{
		"word_id": wordID,
	})
}

func livecommentResponse(model LivecommentModel, user User, livestream Livestream) Livecomment {
	return Livecomment{
		ID:         model.ID,
		User:       user,
		Livestream: livestream,
		Comment:    model.Comment,
		Tip:        model.Tip,
		CreatedAt:  model.CreatedAt,
	}
}

func livecommentReportResponse(reportModel LivecommentReportModel, reporter User, comment Livecomment) LivecommentReport {
	return LivecommentReport{
		ID:          reportModel.ID,
		Reporter:    reporter,
		Livecomment: comment,
		CreatedAt:   reportModel.CreatedAt,
	}
}

func getReportableLivecomment(ctx context.Context, tx *sqlx.Tx, comment *LivecommentModel, streamID, commentID int64) error {
	err := tx.GetContext(ctx, comment, "SELECT * FROM livecomments WHERE id = ? AND livestream_id = ?", commentID, streamID)
	if errors.Is(err, sql.ErrNoRows) {
		return tx.GetContext(ctx, comment, "SELECT * FROM moderated_livecomments WHERE id = ? AND livestream_id = ?", commentID, streamID)
	}
	return err
}
